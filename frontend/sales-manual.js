const PANEL_WORDS = [
  ['品名・材質・板厚・数量・単価', '盤名称・型式仕様・電圧容量・面数・単価'],
  ['塗装対応がなくて失注した金額の合計', '屋外盤の防水・塩害対応がなくて失注した金額の合計'],
];

// この会社で見せる章（ブループリントのない会社には出さない・和宏電機は盤向け）。章番号は詰め直す
function manualList() {
  const hasBp = S.meta && S.meta.pipelines && S.meta.pipelines.some(p => p.key === 'bp');
  const panel = typeof isPanel === 'function' && isPanel();
  let list = MANUAL.filter(m => hasBp || m.id !== 'bp');
  if (panel) {
    list = list.map(m => {
      let html = m.id === 'checks' ? PANEL_CHECKS_HTML : m.html;
      PANEL_WORDS.forEach(([a, b]) => { html = html.split(a).join(b); });
      return { ...m, html, title: m.id === 'checks' ? m.title.replace('当社版BANT', '盤の営業版') : m.title };
    });
    PANEL_CHAPTERS.forEach(ch => {
      const i = list.findIndex(m => m.id === ch.after);
      list.splice(i + 1, 0, { ...ch, title: '0. ' + ch.title });
    });
  }
  return list.map((m, i) => ({ ...m, title: m.title.replace(/^\d+\.\s*/, `${i + 1}. `) }));
}

function manualSectionFor(principle) {
  return manualList().find(m => m.tags.includes(principle)) || null;
}

function openManual(principle = null) {
  const sec = principle ? manualSectionFor(principle) : null;
  setView('manual');
  if (sec) setTimeout(() => {
    const el = document.getElementById('man-' + sec.id);
    if (el) { el.scrollIntoView({ behavior: 'smooth', block: 'start' }); el.classList.add('man-flash'); setTimeout(() => el.classList.remove('man-flash'), 1600); }
  }, 50);
}

